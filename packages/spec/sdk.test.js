import { afterEach, describe, expect, test } from "bun:test";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { checkReadme, checkSpecHash, hashSpec } from "./sdk.mjs";

const SPEC = "openapi: 3.1.0\ninfo:\n  title: Test\n  version: 1.0.0\n";
const README = "# Memtavi SDK\n\nGenerated by Fern.\n";
const directories = [];

function workspace() {
  const directory = mkdtempSync(join(tmpdir(), "sdk-hash-"));
  directories.push(directory);
  const specPath = join(directory, "openapi.yaml");
  const hashPath = join(directory, "spec.sha256");
  const readmeSourcePath = join(directory, "source-README.md");
  const readmeRootPath = join(directory, "README.md");
  writeFileSync(specPath, SPEC);
  writeFileSync(readmeSourcePath, README);
  return { specPath, hashPath, readmeSourcePath, readmeRootPath };
}

afterEach(() => {
  while (directories.length > 0) rmSync(directories.pop(), { recursive: true, force: true });
});

describe("sdk hash check", () => {
  test("accepts a hash that matches the spec", () => {
    const { specPath, hashPath } = workspace();
    writeFileSync(hashPath, `${hashSpec(specPath)}\n`);

    expect(checkSpecHash({ specPath, hashPath })).toEqual({
      ok: true,
      actual: hashSpec(specPath),
    });
  });

  test("rejects a spec that gained a trailing blank line", () => {
    const { specPath, hashPath } = workspace();
    const committed = hashSpec(specPath);
    writeFileSync(hashPath, `${committed}\n`);
    writeFileSync(specPath, `${SPEC}\n`);

    const result = checkSpecHash({ specPath, hashPath });

    expect(result.ok).toBe(false);
    expect(result.reason).toBe("stale");
    expect(result.expected).toBe(committed);
    expect(result.actual).toBe(hashSpec(specPath));
    expect(result.actual).not.toBe(committed);
  });

  test("reports a missing hash file", () => {
    const { specPath, hashPath } = workspace();

    const result = checkSpecHash({ specPath, hashPath });

    expect(result.ok).toBe(false);
    expect(result.reason).toBe("missing");
    expect(result.actual).toBe(hashSpec(specPath));
  });
});

describe("sdk readme check", () => {
  test("accepts a package README identical to the generated one", () => {
    const { readmeSourcePath, readmeRootPath } = workspace();
    writeFileSync(readmeRootPath, README);

    expect(checkReadme({ sourcePath: readmeSourcePath, rootPath: readmeRootPath })).toEqual({
      ok: true,
    });
  });

  test("rejects a package README that drifted from the generated one", () => {
    const { readmeSourcePath, readmeRootPath } = workspace();
    writeFileSync(readmeRootPath, `${README}\nstale\n`);

    const result = checkReadme({ sourcePath: readmeSourcePath, rootPath: readmeRootPath });

    expect(result.ok).toBe(false);
    expect(result.reason).toBe("differ");
  });

  test("reports a missing package README", () => {
    const { readmeSourcePath, readmeRootPath } = workspace();

    const result = checkReadme({ sourcePath: readmeSourcePath, rootPath: readmeRootPath });

    expect(result.ok).toBe(false);
    expect(result.reason).toBe("missing");
  });
});
